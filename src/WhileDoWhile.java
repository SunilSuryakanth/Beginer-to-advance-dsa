public class WhileDoWhile {
    public static void main(String[] args) {

        int i = 10;
        while (i < 9) {
            System.out.println("Sunil koule");
            i++;
        }

        int j = 10;
        do {
            System.out.println("Sunil koule");
            j++;
        } while (j<9);
    }
}
